-- digests 목록에서 고정 제목("하루의 스터디 정리") 대신 AI가 생성한 그날의
-- 한 줄 요약(one_liner)을 제목으로 쓰기 위해 컬럼을 추가한다.
-- body_md 안의 '## 오늘의 한 줄' 섹션과 같은 값이지만, 목록 화면에서 body_md
-- 전체를 불러오지 않고도 제목만 가볍게 조회할 수 있도록 별도 컬럼으로 둔다.
--
-- 이 마이그레이션 이전에 생성된 정리본은 one_liner가 NULL이며, 화면에서는
-- 기존 고정 문구로 폴백한다. 과거 행을 채우고 싶다면 body_md를 다시 파싱해
-- 별도로 백필해야 한다(이 마이그레이션에는 포함하지 않음).

alter table public.digests
  add column one_liner text;
